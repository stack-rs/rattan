#!/usr/bin/env python3

from __future__ import annotations

import argparse
import itertools
import json
from pathlib import Path

BYTES_PER_PACKET = 1500


def bytes_per_ms(mbps: float) -> float:
    return mbps * 125.0


DENSITY_TRACE_STEPS = [(1.5, 20), (0.5, 10), (1.1, 30), (0.8, 40)]


def check_trace_mean(steps: list[tuple[float, int]]) -> None:
    total_ms = sum(d for _, d in steps)
    mean = sum(m * d for m, d in steps) / total_ms
    if abs(mean - 1.0) > 1e-9:
        raise ValueError(f"trace steps average to {mean:.6f} of the target, not 1.0")


def rattan_config(uplink: list[dict], downlink: list[dict]) -> str:
    out = [
        "# Generated by lib/gen-scenarios.py. Do not edit.",
        "",
        "[env]",
        'mode = "Isolated"',
        "left_veth_count = 1",
        "right_veth_count = 1",
        "",
    ]

    for cell in uplink + downlink:
        out.append(f"[cells.{cell['name']}]")
        for key, value in cell["body"]:
            out.append(f"{key} = {value}")
        out.append("")

    out.append("[links]")
    up = ["left"] + [c["name"] for c in uplink] + ["right"]
    down = ["right"] + [c["name"] for c in downlink] + ["left"]
    for chain in (up, down):
        for src, dst in itertools.pairwise(chain):
            out.append(f'{src} = "{dst}"')
    out.append("")
    return "\n".join(out)


def rattan_delay(name: str, delay_ms: float) -> dict:
    return {"name": name, "body": [("type", '"Delay"'), ("delay", f'"{delay_ms}ms"')]}


def rattan_loss(name: str, rate: float) -> dict:
    return {"name": name, "body": [("type", '"Loss"'), ("pattern", f"[{rate}]")]}


def rattan_bandwidth(name: str, mbps: float, queue_bytes: int | None) -> dict:
    body = [("type", '"Bw"'), ("bandwidth", f'"{mbps}Mbps"')]
    if queue_bytes is None:
        body.append(("queue", '"Infinite"'))
    else:
        body += [
            ("queue", '"DropTail"'),
            ("queue_config", f"{{ byte_limit = {queue_bytes} }}"),
        ]
    return {"name": name, "body": body}


def rattan_bandwidth_replay(name: str, trace: str, queue_bytes: int) -> dict:
    return {
        "name": name,
        "body": [
            ("type", '"BwReplay"'),
            ("trace", f'"{trace}"'),
            ("queue", '"DropTail"'),
            ("queue_config", f"{{ byte_limit = {queue_bytes} }}"),
        ],
    }


def rattan_bandwidth_trace(steps: list[tuple[float, int]], mean_mbps: float) -> dict:
    return {
        "RepeatedBwPatternConfig": {
            "pattern": [
                {
                    "TraceBwConfig": {
                        "pattern": [
                            [f"{duration}ms", [f"{multiple * mean_mbps:.3f}Mbps"]]
                            for multiple, duration in steps
                        ]
                    }
                }
            ],
            "count": 0,
        }
    }


def mahimahi_link(trace: str, queue_bytes: int | None) -> list[str]:
    cmd = ["mm-link", trace, trace]
    if queue_bytes is not None:
        cmd += [
            "--uplink-queue=droptail",
            f"--uplink-queue-args=bytes={queue_bytes}",
            "--downlink-queue=droptail",
            f"--downlink-queue-args=bytes={queue_bytes}",
        ]
    return cmd


def mahimahi_trace(schedule: list[int], max_ms: int) -> str:
    lines: list[int] = []
    credit = 0
    ms = 0
    while ms < max_ms:
        credit += schedule[ms % len(schedule)]
        ms += 1
        while credit >= BYTES_PER_PACKET:
            credit -= BYTES_PER_PACKET
            lines.append(ms)
        if credit == 0 and ms % len(schedule) == 0:
            break
    else:
        raise ValueError(
            f"no seamless {max_ms} ms trace for this bandwidth; "
            "pick one whose byte rate divides evenly by 1500"
        )
    return "\n".join(str(t) for t in lines) + "\n"


def mahimahi_static_trace(mbps: float) -> str:
    per_ms = bytes_per_ms(mbps)
    if per_ms != int(per_ms):
        raise ValueError(f"{mbps} Mbps is not a whole number of bytes per ms")
    return mahimahi_trace([int(per_ms)], max_ms=10_000)


def mahimahi_stepped_trace(steps: list[tuple[float, int]], mean_mbps: float) -> str:
    schedule: list[int] = []
    for multiple, duration in steps:
        per_ms = bytes_per_ms(multiple * mean_mbps)
        if abs(per_ms - round(per_ms)) > 1e-6:
            raise ValueError(
                f"step {multiple}x{mean_mbps} Mbps is not a whole number of bytes per ms"
            )
        schedule += [round(per_ms)] * duration
    return mahimahi_trace(schedule, max_ms=10_000)


MININET_UNLIMITED_QUEUE_PKTS = 10_000_000


def mininet_topology(links: list[dict]) -> dict:
    for index, link in enumerate(links):
        link["from"] = "h1" if index == 0 else f"s{index}"
        link["to"] = "h2" if index == len(links) - 1 else f"s{index + 1}"
    return {
        "links": links,
        "commands": {
            "h1": {"cmd": ["lib/iperf3-client.sh"], "print": True},
            "h2": {"cmd": ["lib/iperf3-server.sh"], "env": {"NO_WAIT": "1"}},
        },
    }


def mininet_link(
    delay_ms: float,
    bw_mbps: float | None = None,
    loss: float | None = None,
    queue_bytes: int | None = None,
    queue_pkts: int | None = None,
) -> dict:
    side: dict = {"delay_ms": delay_ms}
    if loss is not None:
        side["loss"] = loss
    if queue_bytes is not None:
        side["max_queue_bytes"] = queue_bytes
    elif queue_pkts is not None:
        side["max_queue_pkts"] = queue_pkts
    down = dict(side)
    if bw_mbps is not None:
        down["bw_Mbps"] = bw_mbps
    return {"uplink": side, "downlink": down}


def write(outdir: Path, name: str, suffix: str, content: str) -> None:
    (outdir / f"{name}{suffix}").write_text(content)


def build_throughput(outdir: Path, bandwidth_mbps: float, delay_ms: float) -> str:
    name = f"tput-{int(bandwidth_mbps)}mbps"

    write(
        outdir,
        name,
        ".toml",
        rattan_config(
            uplink=[rattan_delay("uplink-delay1", delay_ms)],
            downlink=[
                rattan_bandwidth("downlink-bandwidth1", bandwidth_mbps, None),
                rattan_delay("downlink-delay1", delay_ms),
            ],
        ),
    )

    write(outdir, name, ".mm.trace", mahimahi_static_trace(bandwidth_mbps))
    cmd = mahimahi_link(f"{name}.mm.trace", None) + ["mm-delay", str(int(delay_ms))]
    write(outdir, name, ".mm", " ".join(cmd) + "\n")

    write(
        outdir,
        name,
        ".json",
        json.dumps(
            mininet_topology(
                [
                    mininet_link(
                        delay_ms,
                        bw_mbps=bandwidth_mbps,
                        queue_pkts=MININET_UNLIMITED_QUEUE_PKTS,
                    )
                ]
            ),
            indent=2,
        )
        + "\n",
    )
    return name


def build_complexity(
    outdir: Path, depth: int, delay_ms: float, bandwidth_mbps: float
) -> str:
    name = f"complexity-{depth}"

    uplink = [rattan_delay("uplink-delay1", delay_ms)]
    downlink = [rattan_delay("downlink-delay1", delay_ms)]
    for i in range(1, depth + 1):
        uplink += [
            rattan_loss(f"uplink-loss{i}", 0.0),
            rattan_delay(f"uplink-delay{i + 1}", 1),
        ]
        downlink += [
            rattan_loss(f"downlink-loss{i}", 0.0),
            rattan_bandwidth(f"downlink-bandwidth{i}", bandwidth_mbps, None),
            rattan_delay(f"downlink-delay{i + 1}", 1),
        ]
    write(outdir, name, ".toml", rattan_config(uplink, downlink))

    write(outdir, name, ".mm.trace", mahimahi_static_trace(bandwidth_mbps))
    cmd = ["mm-delay", str(int(delay_ms))]
    for _ in range(depth):
        cmd += ["mm-loss", "uplink", "0.0", "mm-loss", "downlink", "0.0"]
        cmd += mahimahi_link(f"{name}.mm.trace", None)
        cmd += ["mm-delay", "1"]
    write(outdir, name, ".mm", " ".join(cmd) + "\n")

    links = [mininet_link(delay_ms, queue_pkts=MININET_UNLIMITED_QUEUE_PKTS)]
    for _ in range(depth):
        links.append(
            mininet_link(
                1,
                bw_mbps=bandwidth_mbps,
                loss=0.0,
                queue_pkts=MININET_UNLIMITED_QUEUE_PKTS,
            )
        )
    write(outdir, name, ".json", json.dumps(mininet_topology(links), indent=2) + "\n")
    return name


def build_density(
    outdir: Path, mode: str, bandwidth_mbps: float, delay_ms: float
) -> str:
    name = f"density-{int(bandwidth_mbps)}mbps-{mode}"
    rtt_ms = 2 * delay_ms
    queue_bytes = int(bandwidth_mbps * 125 * rtt_ms * 2)

    if mode == "static":
        bw_cell = rattan_bandwidth("downlink-bandwidth1", bandwidth_mbps, queue_bytes)
        mm_trace = mahimahi_static_trace(bandwidth_mbps)
    else:
        check_trace_mean(DENSITY_TRACE_STEPS)
        write(
            outdir,
            name,
            "-bw.json",
            json.dumps(
                rattan_bandwidth_trace(DENSITY_TRACE_STEPS, bandwidth_mbps), indent=2
            )
            + "\n",
        )
        bw_cell = rattan_bandwidth_replay(
            "downlink-bandwidth1", f"{name}-bw.json", queue_bytes
        )
        mm_trace = mahimahi_stepped_trace(DENSITY_TRACE_STEPS, bandwidth_mbps)

    write(
        outdir,
        name,
        ".toml",
        rattan_config(
            uplink=[rattan_delay("uplink-delay1", delay_ms)],
            downlink=[
                bw_cell,
                rattan_loss("downlink-loss1", 0.0),
                rattan_delay("downlink-delay1", delay_ms),
            ],
        ),
    )

    write(outdir, name, ".mm.trace", mm_trace)
    cmd = (
        mahimahi_link(f"{name}.mm.trace", queue_bytes)
        + ["mm-loss", "uplink", "0.0"]
        + ["mm-delay", str(int(delay_ms))]
    )
    write(outdir, name, ".mm", " ".join(cmd) + "\n")

    write(
        outdir,
        name,
        ".json",
        json.dumps(
            mininet_topology(
                [
                    mininet_link(
                        delay_ms,
                        bw_mbps=bandwidth_mbps,
                        loss=0.0,
                        queue_bytes=queue_bytes,
                    )
                ]
            ),
            indent=2,
        )
        + "\n",
    )
    return name


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("outdir", type=Path, help="directory to write into")
    sub = parser.add_subparsers(dest="scenario", required=True)

    p = sub.add_parser("throughput", help="Figure 5")
    p.add_argument("--bandwidth-mbps", type=float, required=True)
    p.add_argument("--delay-ms", type=float, default=25)

    p = sub.add_parser("complexity", help="Figure 6")
    p.add_argument("--depth", type=int, required=True)
    p.add_argument("--delay-ms", type=float, default=25)
    p.add_argument("--bandwidth-mbps", type=float, default=1000)

    p = sub.add_parser("density", help="Figure 7")
    p.add_argument("--mode", choices=["static", "trace"], required=True)
    p.add_argument("--bandwidth-mbps", type=float, default=16)
    p.add_argument("--delay-ms", type=float, default=20)

    args = parser.parse_args()
    args.outdir.mkdir(parents=True, exist_ok=True)

    if args.scenario == "throughput":
        name = build_throughput(args.outdir, args.bandwidth_mbps, args.delay_ms)
    elif args.scenario == "complexity":
        if args.depth < 1:
            parser.error("--depth must be at least 1")
        name = build_complexity(
            args.outdir, args.depth, args.delay_ms, args.bandwidth_mbps
        )
    else:
        name = build_density(args.outdir, args.mode, args.bandwidth_mbps, args.delay_ms)

    print(name)


if __name__ == "__main__":
    main()
